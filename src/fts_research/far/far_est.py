"""Estimation and inference for a FAR(1) process, the counterpart to `far_dgp`'s simulation.

    X_t(s) = int psi(s, r) X_{t-1}(r) dr + eps_t(s)

`far1_fit` estimates psi by the standard FPCA route (Bosq, 2000, ch. 8): project the centred
curves onto their leading `p` empirical principal components, regress each score vector on its
predecessor, and read the kernel back off the resulting `p x p` matrix. The awkward part of
the problem is that the covariance operator has to be inverted and its eigenvalues decay to
zero, so `p` is a regularisation parameter and not a detail -- `select_p` chooses it by
one-step-ahead forecast error on a held-out tail rather than by a variance-explained rule of
thumb, which has no reason to know anything about the *dynamics*.

Two tests answer "is there any serial dependence here at all", which is the question that
has to be settled before a fitted `Psi` means anything:

`portmanteau_test`   the multivariate Ljung-Box statistic of Gabrys & Kokoszka (2007),
                     generalising Ljung & Box (1978), computed on the score vectors and
                     referred to its chi-squared limit;
`permutation_test`   the same autocovariance norms referred instead to the distribution
                     generated by reshuffling the curves, which is the i.i.d. null exactly,
                     conditional on the observed marginal, and assumes nothing about tails
                     or moments.

The second matters here because financial curves are heavy tailed and the chi-squared limit
leans on fourth moments. Where the two disagree, the permutation reference is the one to
believe.

`rolling_forecast` scores a fitted model the only way that settles anything on real data:
one step ahead, out of sample, refitting on an expanding window, against the flat forecast.
"""

import numpy as np

from ..core.quadrature import quadrature_weights

